    /**
     * @return array<string, int|string>
     */
    private function monster(
        string $slug,
        string $name,
        int $level,
        int $rank,
        int $experience,
        string $sprite,
        int $sortOrder,
    ): array {
        $earlyStarterBand = $level <= 10 && $rank <= 2;
        $earlyHealthRelief = $earlyStarterBand ? 4 + intdiv(max(0, 10 - $level), 2) : 0;
        $earlyAttackRelief = $earlyStarterBand ? ($level <= 4 ? 1 : 0) : 0;
        $maximumHealth = max(
            10,
            16 + ($level * 5) + ($rank * 12) + (int) floor($experience / 30) - $earlyHealthRelief,
        );
        $minimumAttack = max(3, 3 + (int) floor($level * 0.9) + ($rank * 2) - $earlyAttackRelief);
        $maximumAttack = max($minimumAttack + 2, $minimumAttack + 3 + $rank - $earlyAttackRelief);
        $defense = max(0, (int) floor($level / 4) + $rank - 1);
        $yangMin = max(3, (int) floor($experience / 4));
        $yangMax = max($yangMin + 2, (int) floor($experience / 3));

        return [
            'slug' => $slug,
            'name' => $name,
            'level' => $level,
            'rank' => $rank,
            'race' => 'Tiere',
            'damage_type' => 'Physisch',
            'sprite' => $sprite,
            'maximum_health' => $maximumHealth,
            'minimum_attack' => $minimumAttack,
            'maximum_attack' => $maximumAttack,
            'defense' => $defense,
            'experience_reward' => $experience,
            'yang_min' => $yangMin,
            'yang_max' => $yangMax,
            'sort_order' => $sortOrder,
        ];
    }

