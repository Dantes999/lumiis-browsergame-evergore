            54 => ['himmelstraenenhalskette', 'himmelstraenenarmband', 'himmelstraenenohrringe', 'phoenixschuhe'],
            60 => ['seelenkristallkette', 'seelenkristallarmband', 'seelenkristallohrringe', 'drachenschuppenschild', 'falkenschild'],
            65 => ['euphorieschuhe', 'glorienstiefel', 'qilinschuhe', 'dreikaiserschild', 'loewenkantenschild', 'tigerschild'],
            80 => ['feuerschuhe', 'titanenschild', 'kriegsmeisterhelm', 'magischer-helm', 'spinnenkapuze'],
            90 => ['ozeanschuhe', 'verdammnis-schild', 'gruenwaldhelm', 'seelensplitterhut'],
        ];

        $candidateSlugs = collect($tiers)
            ->filter(fn (array $slugs, int $minLevel): bool => $recommendedLevel >= $minLevel)
            ->sortKeysDesc()
            ->flatten()
            ->unique()
            ->values();

        if ($candidateSlugs->isEmpty()) {
            return [];
        }

        $chance = $encounterType === 'boss' ? 520 : 320;
        $limit = $encounterType === 'boss' ? 6 : 4;

        return $candidateSlugs
            ->take($limit)
            ->map(fn (string $slug): array => $this->loot($slug, $chance))
            ->all();
    }

    /**
     * @return array{slug: string, chance: int, min: int, max: int}
     */
    private function loot(string $slug, int $chance, int $min = 1, int $max = 1): array
    {
        return [
            'slug' => $slug,
            'chance' => $chance,
            'min' => $min,
            'max' => $max,
        ];
    }

    /**
     * Skill books drop from Lumiis stones and bosses so the later rank loop feeds back into hunting.
     *
     * @param  array<string, mixed>  $area
     * @return list<array{slug: string, chance: int, min: int, max: int}>
     */
    private function skillBookLootTableForArea(array $area, string $encounterType): array
    {
        $recommendedLevel = max(1, (int) ($area['recommended_level'] ?? 1));

        if ($recommendedLevel < 5) {
            return [];
        }

        $chance = match ($encounterType) {
            'boss' => $recommendedLevel >= 20 ? 1800 : 1400,
            default => $recommendedLevel >= 12 ? 900 : 650,
        };

        return [
            $this->loot(MetinClassCatalog::matchingSkillBookRewardToken(), $chance),
        ];
    }

    /**
     * Soul Stones start on bosses once areas move into the real midgame.
     *
     * Keeping them boss-focused makes the G/P climb a reward for mastered map loops
     * instead of another generic low-level field drop.
     *
     * @param  array<string, mixed>  $area
     * @return list<array{slug: string, chance: int, min: int, max: int}>
     */
    private function soulStoneLootTableForArea(array $area, string $encounterType): array
    {
        $recommendedLevel = max(1, (int) ($area['recommended_level'] ?? 1));

        if ($encounterType !== 'boss' || $recommendedLevel < 7) {
            return [];
        }

        return [
            $this->loot(
                MetinClassCatalog::soulStoneSlug(),
                $recommendedLevel >= 15 ? 1800 : 1200,
            ),
        ];
    }

