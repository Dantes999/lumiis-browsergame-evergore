    private function seedItemBonusDefinitions(\Illuminate\Support\Carbon $timestamp): void
    {
        $bonusDefinitions = [];

        foreach (ItemBonusCatalog::defaultDefinitions() as $bonusType => $definition) {
            $bonusDefinitions[] = [
                'bonus_type' => $bonusType,
                'label' => $definition['label'],
                'minimum_value' => $definition['min'],
                'maximum_value' => $definition['max'],
                'suffix' => $definition['suffix'],
                'allowed_slots' => json_encode($definition['slots'], JSON_THROW_ON_ERROR),
                'enabled' => true,
                'sort_order' => count($bonusDefinitions) * 10 + 10,
                'created_at' => $timestamp,
                'updated_at' => $timestamp,
            ];
        }

        ItemBonusDefinition::query()->upsert(
            $bonusDefinitions,
            ['bonus_type'],
            ['label', 'minimum_value', 'maximum_value', 'suffix', 'allowed_slots', 'enabled', 'sort_order', 'updated_at'],
        );

        ItemBonusDefinition::flushRuntimeCache();
    }

